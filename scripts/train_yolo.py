"""Run a reproducible Ultralytics training job on a frozen dataset YAML."""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import subprocess
from datetime import datetime
from pathlib import Path

import torch
import ultralytics
from ultralytics import YOLO

from defectaug.data_lock import maybe_verify_content_lock


PROJECT = Path(__file__).resolve().parents[1]


def sha256_file(path: Path, chunk_size: int = 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(chunk_size), b""):
            digest.update(block)
    return digest.hexdigest()


def project_path(value: str) -> Path:
    path = Path(value).expanduser()
    return path.resolve() if path.is_absolute() else (PROJECT / path).resolve()


def git_commit() -> str | None:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=PROJECT, text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", default="configs/dataset_sd900_3class_v2.yaml")
    parser.add_argument("--model", default="yolo11n.pt")
    parser.add_argument("--epochs", type=int, default=3)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--batch", type=int, default=16)
    parser.add_argument("--device", default="0")
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--seed", type=int, default=20260820)
    parser.add_argument("--name", default="smoke_real_only")
    parser.add_argument(
        "--optimizer",
        choices=("SGD", "Adam", "AdamW", "NAdam", "RAdam", "RMSProp"),
        default="SGD",
        help="Explicit optimizer; auto-selection is disallowed for formal comparisons.",
    )
    parser.add_argument("--lr0", type=float, default=0.01)
    parser.add_argument("--lrf", type=float, default=0.01)
    parser.add_argument("--momentum", type=float, default=0.937)
    parser.add_argument("--weight-decay", type=float, default=0.0005)
    parser.add_argument("--warmup-epochs", type=float, default=3.0)
    parser.add_argument("--amp", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument(
        "--allow-model-download",
        action="store_true",
        help="Permit a missing model name to be downloaded; never use for a frozen formal run.",
    )
    parser.add_argument(
        "--content-lock",
        default="data/manifests/dataset_content_lock_v2.json",
        help="Byte-level image/label/mask lock generated by freeze_dataset_content.py.",
    )
    parser.add_argument(
        "--content-lock-mode",
        choices=("required", "optional", "off"),
        default="required",
        help="Verify train_fewshot and val content before and after training.",
    )
    args = parser.parse_args()

    if not torch.cuda.is_available() and args.device != "cpu":
        raise RuntimeError("CUDA is unavailable in this environment; refusing silent CPU training")
    if args.epochs <= 0 or args.imgsz <= 0 or args.batch <= 0 or args.workers < 0:
        raise ValueError("epochs, imgsz and batch must be positive; workers cannot be negative")
    if args.lr0 <= 0 or args.lrf <= 0 or args.weight_decay < 0 or args.warmup_epochs < 0:
        raise ValueError("invalid optimizer schedule parameters")

    data_yaml = project_path(args.data)
    content_lock = project_path(args.content_lock)
    content_verification = maybe_verify_content_lock(
        content_lock,
        project_root=PROJECT,
        splits=("train_fewshot", "val"),
        mode=args.content_lock_mode,
        expected_data_yaml=data_yaml,
    )

    model_path = project_path(args.model)
    if model_path.is_file():
        model_source = str(model_path)
        initial_model_sha256 = sha256_file(model_path)
    elif args.allow_model_download:
        model_source = args.model
        initial_model_sha256 = None
    else:
        raise FileNotFoundError(
            f"pinned local pretrained model is required: {model_path}; "
            "--allow-model-download is for setup runs only"
        )

    run_root = PROJECT / "runs" / "yolo"
    metadata = {
        "started_at": datetime.now().astimezone().isoformat(),
        "python": platform.python_version(),
        "platform": platform.platform(),
        "torch": torch.__version__,
        "torch_cuda": torch.version.cuda,
        "cuda_available": torch.cuda.is_available(),
        "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else None,
        "ultralytics": ultralytics.__version__,
        "git_commit": git_commit(),
        "initial_model": {
            "requested": args.model,
            "resolved": model_source,
            "sha256": initial_model_sha256,
        },
        "arguments": vars(args),
        "dataset_content_lock": (
            content_verification.as_dict() if content_verification is not None else None
        ),
    }
    run_root.mkdir(parents=True, exist_ok=True)
    (run_root / f"{args.name}_launch.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    model = YOLO(model_source)
    model.train(
        data=str(data_yaml),
        epochs=args.epochs,
        imgsz=args.imgsz,
        batch=args.batch,
        device=args.device,
        workers=args.workers,
        seed=args.seed,
        deterministic=True,
        project=str(run_root),
        name=args.name,
        exist_ok=False,
        patience=0,
        optimizer=args.optimizer,
        lr0=args.lr0,
        lrf=args.lrf,
        momentum=args.momentum,
        weight_decay=args.weight_decay,
        warmup_epochs=args.warmup_epochs,
        amp=args.amp,
        cache=False,
        plots=True,
        save=True,
        verbose=True,
        # Mild, fixed label-preserving native augmentation.  Heavy composition is
        # disabled so it cannot obscure the contribution of generated samples.
        hsv_h=0.0,
        hsv_s=0.0,
        hsv_v=0.20,
        degrees=5.0,
        translate=0.05,
        scale=0.20,
        shear=0.0,
        perspective=0.0,
        flipud=0.0,
        fliplr=0.5,
        mosaic=0.0,
        mixup=0.0,
        copy_paste=0.0,
    )
    final_content_verification = maybe_verify_content_lock(
        content_lock,
        project_root=PROJECT,
        splits=("train_fewshot", "val"),
        mode=args.content_lock_mode,
        expected_data_yaml=data_yaml,
    )
    if content_verification != final_content_verification:
        raise RuntimeError("dataset content-lock verification changed during training")


if __name__ == "__main__":
    main()
